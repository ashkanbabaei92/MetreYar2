export function parseFehrestText(text: string): { rows: FehrestRow[]; skipped: number } {
  const lines = text.split(/\r?\n/);
  const rows: FehrestRow[] = [];
  let skipped = 0;

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line) continue;

    // جدا کردن سلول‌ها بر اساس تب یا ویرگول
    const cells = (line.includes("\t") ? line.split("\t") : line.split(/,(?=(?:[^"]*"[^"]*")*[^"]*$)/))
      .map((c) => c.replace(/^"|"$/g, "").trim());

    if (cells.length < 2) continue;

    // یافتن کد ردیف (شش رقم)
    const codeIdx = cells.findIndex((c) => /^\d{6}$/.test(toEnSafe(c)));
    if (codeIdx < 0) {
      skipped++;
      continue;
    }

    const code = toEnSafe(cells[codeIdx]);
    const after = cells.slice(codeIdx + 1).filter(Boolean);

    let chapter = code.slice(0, 2);
    let desc = "";
    let unit = "";
    let price = 0;

    // فصل: اولین سلول دو رقمی بعد از کد
    const chIdx = after.findIndex((c) => /^\d{1,2}$/.test(toEnSafe(c)));
    const contentCells = chIdx >= 0 ? after.slice(chIdx + 1) : after;
    if (chIdx >= 0) chapter = toEnSafe(after[chIdx]).padStart(2, "0");

    // قیمت: آخرین سلول عددیِ سطر
    const nums = contentCells.map(parseCellNumber);
    let priceIdx = -1;
    for (let i = nums.length - 1; i >= 0; i--) {
      if (nums[i] !== null && nums[i] !== 0) {
        priceIdx = i;
        price = nums[i]!;
        break;
      }
    }

    // واحد: سلولی که با واژهٔ واحد شروع می‌شود
    const textCells = contentCells.filter((c) => parseCellNumber(c) === null);
    for (const c of contentCells) {
      const w = c.replace(/["«»]/g, "").trim();
      if (UNIT_WORDS.some((u) => w === u || w.startsWith(u + " ") || w.startsWith(u + "-"))) {
        unit = w;
        break;
      }
    }

    desc = textCells
      .filter((c) => c !== unit && normalizeSpace(c).length > 2)
      .sort((a, b) => b.length - a.length)[0];
    desc = normalizeSpace(desc || textCells[0] || "");

    if (!desc || desc.length < 5) {
      skipped++;
      continue;
    }
    if (!unit) unit = guessUnitFromDesc(desc);
    if (priceIdx < 0) price = 0;

    rows.push({ code, chapter, desc, unit, price, estimated: false });
  }

  // حذف تکراری‌ها (کد یکتا)
  const seen = new Set<string>();
  const unique = rows.filter((r) => (seen.has(r.code) ? false : (seen.add(r.code), true)));
  return { rows: unique, skipped };
}

export function toEnSafe(s: string): string {
  const fa = "۰۱۲۳۴۵۶۷۸۹";
  const ar = "٠١٢٣٤٥٦٧٨٩";
  let out = "";
  for (const ch of s) {
    const i = fa.indexOf(ch);
    if (i >= 0) { out += String(i); continue; }
    const j = ar.indexOf(ch);
    if (j >= 0) { out += String(j); continue; }
    out += ch;
  }
  return out;
}

function parseCellNumber(c: string): number | null {
  const t = toEnSafe(c).replace(/[,٬\s]/g, "");
  if (!/^-?\d+(\.\d+)?$/.test(t)) return null;
  const v = parseFloat(t);
  return Number.isFinite(v) ? v : null;
}

function normalizeSpace(s: string): string {
  return s.replace(/["«»]/g, " ").replace(/\s+/g, " ").trim();
}

function guessUnitFromDesc(desc: string): string {
  if (/کیلوگرم|وزن|آهن|میلگرد/.test(desc)) return "کیلوگرم";
  if (/مترمکعب|حجم|خاک|بتن/.test(desc)) return "مترمکعب";
  if (/مترطول|طول/.test(desc)) return "مترطول";
  return "مترمربع";
}

/** ادغام فهرست آپلودشده با پایگاه تعبیه‌شده (ردیف‌های واقعی جایگزین تخمینی می‌شوند) */
export function mergeFehrest(uploaded: FehrestRow[]): FehrestRow[] {
  const map = new Map<string, FehrestRow>();
  for (const r of EMBEDDED_FEHREST) map.set(r.code, r);
  for (const r of uploaded) map.set(r.code, { ...r, estimated: false });
  return [...map.values()].sort((a, b) => a.code.localeCompare(b.code));
}
