def build_docx(path):
    from docx import Document
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml.ns import qn
    from docx.shared import Pt, Cm

    doc = Document()
    # صفحهٔ RTL و فونتِ فارسی
    style = doc.styles["Normal"]
    style.font.name = "Tahoma"
    style.font.size = Pt(11)
    rpr = style.element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        from docx.oxml import OxmlElement
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        rfonts.set(qn(attr), "Tahoma")

    def rtl(par):
        pPr = par._p.get_or_add_pPr()
        from docx.oxml import OxmlElement
        bidi = OxmlElement("w:bidi")
        pPr.append(bidi)
        par.alignment = WD_ALIGN_PARAGRAPH.RIGHT

    def para(text="", bold=False, size=None, space_after=6):
        p = doc.add_paragraph()
        rtl(p)
        r = p.add_run(text)
        r.bold = bold
        if size:
            r.font.size = Pt(size)
        p.paragraph_format.space_after = Pt(space_after)
        return p

    para("برگهٔ تصمیم — پروژهٔ MetreYar2", bold=True, size=16)
    para("مرتب‌شده بر اساسِ بزرگ‌ترین اثرِ ریالی. اعداد روی پروژهٔ مرجع "
         "(دیسپلین ابنیه). تشریحِ کامل: docs/PENDING_DECISIONS.md", size=9)
    doc.add_paragraph()

    for d in DECISIONS:
        para("%s — %s" % (d["id"], d["title"]), bold=True, size=13)
        para("بند/مرجع: %s" % d["clause"], size=9)
        para("سؤال: %s" % d["question"])
        para("گزینهٔ الف: %s" % d["a"])
        para("گزینهٔ ب: %s" % d["b"])
        para("اثرِ عددی: %s" % d["effect"])
        if d["needs_data"]:
            para("دادهٔ لازم: %s" % d["needs_data"], size=9)
        para("توصیهٔ ما: %s" % d["recommendation"])
        # جدولِ امضا
        t = doc.add_table(rows=2, cols=3)
        t.style = "Table Grid"
        hdr = t.rows[0].cells
        for i, h in enumerate(("تصمیم", "امضا", "تاریخ")):
            p = hdr[i].paragraphs[0]
            rtl(p)
            r = p.add_run(h)
            r.bold = True
        doc.add_paragraph()

    para("تولیدشده با tools/make_decision_sheet.py (فاز E-8 §۵)", size=8)
    doc.save(path)


def main():
    md = build_markdown()
    md_path = os.path.join(ROOT, "docs", "DECISION_SHEET.md")
    with open(md_path, "w", encoding="utf-8") as fh:
        fh.write(md)
    print("wrote", md_path, len(md), "bytes")
    docx_path = os.path.join(ROOT, "docs", "DECISION_SHEET.docx")
    build_docx(docx_path)
    print("wrote", docx_path, os.path.getsize(docx_path), "bytes")


if __name__ == "__main__":
    main()
